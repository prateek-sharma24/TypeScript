//Program using switch case
let x:number=10,y:number=5;
switch(x-y)
{
case 0:
    console.log("Zero");
    break;
    case 1:
    console.log("One");
    break;
    case 2:
    console.log("Two");
    break;
    case 3:
        console.log("Three");
        break;
    case 4:
        console.log("Four");
        break;
    case 5:
        console.log("Five");
        break;
    default:
        console.log("Invalid number");
}